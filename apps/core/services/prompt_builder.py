import re
import logging
import hashlib
import threading

logger = logging.getLogger('specpilot.ai')

class PromptBuilder:
    """
    Handles prompt construction, category-based token budgeting,
    context ranking, redundancy deduplication, and diagnostics reporting.
    """
    _thread_local = threading.local()

    @classmethod
    def get_last_report(cls):
        """
        Returns the diagnostics report generated by the last build_prompt call in the current thread.
        """
        return getattr(cls._thread_local, 'last_report', {})

    @staticmethod
    def sanitize_input(user_input):
        """
        Sanitizes user input to prevent prompt injections, script injections, and raw markdown issues.
        """
        if not user_input:
            return ""
        sanitized = re.sub(r'<[^>]*>', '', user_input)
        return sanitized.strip()

    @classmethod
    def build_prompt(cls, template, **kwargs):
        """
        Injects validated parameters into a prompt template.
        Supports structured context lists, performing ranking, deduplication, and token budgeting.
        """
        sanitized_kwargs = {}
        report = {}
        
        # Check if context_doc is a list of structured dictionaries
        if 'context_doc' in kwargs and isinstance(kwargs['context_doc'], list):
            context_list = kwargs['context_doc']
            
            # 1. Deduplication (Redundancy Detection)
            unique_contexts = []
            seen_hashes = set()
            for item in context_list:
                cleaned_content = item['content'].strip()
                content_hash = hashlib.md5(cleaned_content.encode('utf-8')).hexdigest()
                if content_hash not in seen_hashes:
                    seen_hashes.add(content_hash)
                    unique_contexts.append(item)
            
            # 2. Context Ranking (Highest priority first)
            unique_contexts.sort(key=lambda x: x.get('priority', 5), reverse=True)
            
            # 3. Configurable Token Budget Allocator
            budgets = {
                "project_context": 5000,           # reservation for project metadata and knowledge store facts
                "dependency_summaries": 8000,       # reservation for direct dependency summaries
                "memory": 3000,                     # reservation for short-term chat logs
            }
            
            allocated_tokens = {
                "project_context": 0,
                "dependency_summaries": 0,
                "memory": 0,
            }
            
            selected_items = []
            discarded_items = []
            compressed_items = []
            
            for item in unique_contexts:
                title = item['title']
                content = item['content']
                priority = item['priority']
                reason = item['reason']
                
                # Classify category
                if "Chat" in title or "Memory" in title:
                    category = "memory"
                elif "Project Knowledge" in title:
                    category = "project_context"
                elif "Phase" in title:
                    category = "dependency_summaries"
                else:
                    category = "project_context"
                    
                budget = budgets.get(category, 4000)
                current_tokens = len(content) // 4
                
                # Check budget availability
                if allocated_tokens[category] + current_tokens <= budget:
                    allocated_tokens[category] += current_tokens
                    selected_items.append(item)
                else:
                    # Auto-compress high-priority items, truncate lower priority
                    if priority >= 8:
                        remaining_budget = max(0, budget - allocated_tokens[category])
                        if remaining_budget > 200:
                            char_limit = remaining_budget * 4
                            compressed_content = content[:char_limit] + "\n... [truncated due to budget allocation]"
                            item['content'] = compressed_content
                            compressed_tokens = len(compressed_content) // 4
                            allocated_tokens[category] += compressed_tokens
                            selected_items.append(item)
                            compressed_items.append({
                                "title": title,
                                "original_tokens": current_tokens,
                                "compressed_tokens": compressed_tokens,
                                "reason": f"Category '{category}' budget limit exceeded"
                            })
                        else:
                            discarded_items.append({
                                "title": title,
                                "tokens": current_tokens,
                                "reason": f"Category '{category}' budget exhausted"
                            })
                    else:
                        discarded_items.append({
                            "title": title,
                            "tokens": current_tokens,
                            "reason": f"Low priority ({priority}) discarded to satisfy budget"
                        })
            
            # Format the context block from the selected items
            context_strings = []
            for item in selected_items:
                context_strings.append(
                    f"### {item['title']}\n"
                    f"Selection context: {item['reason']} (Priority: {item['priority']})\n"
                    f"Details:\n{item['content']}"
                )
            
            formatted_context = "\n\n".join(context_strings)
            kwargs['context_doc'] = formatted_context
            
            # Save Prompt Analysis Report on thread local
            total_est_tokens = sum(allocated_tokens.values())
            report = {
                "total_estimated_tokens": total_est_tokens,
                "allocations": allocated_tokens,
                "selected_dependencies": [x['title'] for x in selected_items if "Phase" in x['title']],
                "compressed_context": compressed_items,
                "discarded_context": discarded_items,
                "budget_limits": budgets
            }
            cls._thread_local.last_report = report

        # Standard keyword replacement formatting
        for key, val in kwargs.items():
            if isinstance(val, str):
                sanitized_val = cls.sanitize_input(val)
                if "ignore previous instructions" in sanitized_val.lower() or "system override" in sanitized_val.lower():
                    logger.warning(f"Suspected prompt injection pattern detected in variable '{key}'!")
                    sanitized_val = sanitized_val.replace("ignore previous instructions", "[FILTERED_INJECTION]")
                sanitized_kwargs[key] = sanitized_val
            else:
                sanitized_kwargs[key] = val
        
        try:
            built_prompt = template.format(**sanitized_kwargs)
            # Add estimated template tokens to the diagnostics report
            if report:
                report["total_prompt_tokens"] = report.get("total_estimated_tokens", 0) + (len(built_prompt) // 4)
                cls._thread_local.last_report = report
            return built_prompt
        except KeyError as e:
            logger.error(f"Failed to build prompt template. Missing keyword argument: {str(e)}")
            raise ValueError(f"Required prompt variable {str(e)} was not provided.")
